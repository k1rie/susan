// Genera diccionario.md (y diferencias-spec.json) a partir de la BD viva y de la especificacion.
// Uso: node generar-diccionario.mjs   (requiere la BD local de SUSAN en 127.0.0.1:54329)
import { writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import {
    AREAS, areaDe, columnasDeLaSpec, consultaJson, tipoCorto,
    SQL_COLUMNAS, SQL_INDICES, SQL_POLITICAS, SQL_RESTRICCIONES, SQL_TABLAS, SQL_TRIGGERS,
} from './bd-lib.mjs';

const AQUI = dirname(fileURLToPath(import.meta.url));
const REPO = join(AQUI, '..', '..');

const tablas = consultaJson(SQL_TABLAS);
const columnas = consultaJson(SQL_COLUMNAS);
const restricciones = consultaJson(SQL_RESTRICCIONES);
const indices = consultaJson(SQL_INDICES);
const triggers = consultaJson(SQL_TRIGGERS);
const politicas = consultaJson(SQL_POLITICAS);

const baseTablas = tablas.filter((t) => t.clase === 'r');
const vistas = tablas.filter((t) => t.clase === 'v');

// Toda tabla de la BD debe pertenecer a un area; si no, el mapa AREAS quedo desactualizado.
for (const t of baseTablas) {
    if (!areaDe(t.tabla)) throw new Error(`La tabla ${t.tabla} no figura en AREAS (bd-lib.mjs)`);
}

const spec = columnasDeLaSpec(join(REPO, 'docs', 'spec', 'Avance1.txt'));

const ACCION_BORRADO = { a: 'NO ACTION', r: 'RESTRICT', c: 'CASCADE', n: 'SET NULL', d: 'SET DEFAULT' };

const esc = (s) => String(s).replace(/\|/g, '\\|');
const cod = (s) => '`' + String(s).replace(/`/g, "'") + '`';

function defectoLegible(c) {
    if (c.identidad === 'a') return 'GENERATED ALWAYS AS IDENTITY';
    if (c.identidad === 'd') return 'GENERATED BY DEFAULT AS IDENTITY';
    return c.defecto ? cod(c.defecto) : '';
}

// ---- Diferencias frente a la especificacion (columnas) ----
const diferencias = { tablas_fuera_de_la_spec: [], columnas_extra: [], columnas_faltantes: [], totales: {} };
let colsSpec = 0;
for (const t of baseTablas) {
    const cols = columnas.filter((c) => c.tabla === t.tabla).map((c) => c.columna);
    const s = spec[t.tabla];
    if (!s) { diferencias.tablas_fuera_de_la_spec.push({ tabla: t.tabla, columnas: cols.length }); continue; }
    colsSpec += s.size;
    for (const c of cols) if (!s.has(c)) diferencias.columnas_extra.push({ tabla: t.tabla, columna: c });
    for (const c of s) if (!cols.includes(c)) diferencias.columnas_faltantes.push({ tabla: t.tabla, columna: c });
}
diferencias.totales = {
    tablas_spec: Object.keys(spec).length,
    columnas_spec: colsSpec,
    tablas_bd: baseTablas.length,
    columnas_bd: columnas.filter((c) => baseTablas.some((t) => t.tabla === c.tabla)).length,
};
writeFileSync(join(AQUI, 'diferencias-spec.json'), JSON.stringify(diferencias, null, 2) + '\n');

const esExtra = (tabla, col) => diferencias.columnas_extra.some((e) => e.tabla === tabla && e.columna === col);

// ---- Documento ----
const L = [];
L.push('# Diccionario de datos de SUSAN (generado desde la base de datos)');
L.push('');
L.push('Generado por `generar-diccionario.mjs` consultando el catálogo de PostgreSQL 16 de la base local `susan`');
L.push('(`pg_class`, `pg_attribute`, `pg_constraint`, `pg_index`, `pg_trigger`, `pg_policies`). Nada está escrito a mano:');
L.push('los tipos, nulos, valores por omisión, restricciones e índices son los del catálogo; el propósito de cada tabla es su');
L.push('`COMMENT ON TABLE` (que viene de las migraciones). Los tipos se abrevian (`varchar`, `timestamptz`, `time`).');
L.push('Las expresiones de CHECK se muestran tal como las devuelve `pg_get_constraintdef` (con sus conversiones `::tipo`).');
L.push('');
L.push(`Alcance: ${baseTablas.length} tablas base del esquema \`public\` y la vista \`v_resumen_asistencia\`; al final, las 2 tablas internas del esquema \`app\`.`);
L.push('Marca **[ext]** = columna que no figura en el esquema relacional de la especificación (Avance 1, sección 3.4.1).');
L.push('');
L.push('## Índice');
L.push('');
L.push('| Área | Tablas |');
L.push('|---|---|');
for (const a of AREAS) L.push(`| ${a.id} · ${a.nombre} | ${a.tablas.map((t) => `\`${t}\``).join(', ')} |`);
L.push('');

for (const area of AREAS) {
    L.push(`## Área ${area.id} · ${area.nombre}`);
    L.push('');
    L.push(`Fuente de las tablas: \`${area.fuente}\`.`);
    L.push('');
    for (const nombre of area.tablas) {
        const t = baseTablas.find((x) => x.tabla === nombre);
        const cols = columnas.filter((c) => c.tabla === nombre);
        const rest = restricciones.filter((r) => r.tabla === nombre);
        const enSpec = Boolean(spec[nombre]);
        L.push(`### ${nombre}`);
        L.push('');
        L.push(`**Propósito:** ${t.comentario || '(sin comentario)'}`);
        L.push('');
        L.push(`**En la especificación:** ${enSpec ? 'sí' : 'no (tabla agregada después del Avance 1)'} · **Columnas:** ${cols.length} · **RLS:** ${t.rls ? 'habilitado' : 'no'}`);
        L.push('');
        L.push('| # | Columna | Tipo | Nulo | Por omisión / generación |');
        L.push('|--:|---|---|:-:|---|');
        cols.forEach((c, i) => {
            const marca = enSpec && esExtra(nombre, c.columna) ? ' **[ext]**' : '';
            L.push(`| ${i + 1} | ${cod(c.columna)}${marca} | ${esc(tipoCorto(c.tipo))} | ${c.admite_nulo ? 'sí' : 'no'} | ${esc(defectoLegible(c))} |`);
        });
        L.push('');
        const comentariosCol = cols.filter((c) => c.comentario);
        if (comentariosCol.length) {
            L.push('Comentarios de columna (`COMMENT ON COLUMN`):');
            L.push('');
            for (const c of comentariosCol) L.push(`- ${cod(c.columna)}: ${c.comentario}`);
            L.push('');
        }
        const pk = rest.filter((r) => r.tipo === 'p');
        L.push(`**Llave primaria:** ${pk.map((r) => `${cod(r.nombre)} (${r.columnas.join(', ')})`).join('; ') || '—'}`);
        L.push('');
        const fks = rest.filter((r) => r.tipo === 'f');
        if (fks.length) {
            L.push('**Llaves foráneas:**');
            L.push('');
            L.push('| Restricción | Columnas | Referencia | Al borrar |');
            L.push('|---|---|---|---|');
            for (const r of fks) {
                L.push(`| ${cod(r.nombre)} | ${r.columnas.join(', ')} | ${cod(r.tabla_destino)} (${r.columnas_destino.join(', ')}) | ${ACCION_BORRADO[r.al_borrar]} |`);
            }
            L.push('');
        } else {
            L.push('**Llaves foráneas:** ninguna.');
            L.push('');
        }
        const uqs = rest.filter((r) => r.tipo === 'u');
        const parciales = indices.filter((i) => i.tabla === nombre && i.unico && !i.primario && !i.respalda_restriccion);
        if (uqs.length || parciales.length) {
            L.push('**Únicos:**');
            L.push('');
            for (const r of uqs) L.push(`- ${cod(r.nombre)}: ${r.definicion}`);
            for (const i of parciales) L.push(`- ${cod(i.nombre)} (índice único parcial): ${cod(i.definicion.replace(/^CREATE UNIQUE INDEX \S+ ON /, ''))}`);
            L.push('');
        }
        const cks = rest.filter((r) => r.tipo === 'c');
        if (cks.length) {
            L.push('**Restricciones CHECK:**');
            L.push('');
            for (const r of cks) L.push(`- ${cod(r.nombre)}: ${cod(r.definicion.replace(/^CHECK /, ''))}`);
            L.push('');
        }
        const idx = indices.filter((i) => i.tabla === nombre && !i.primario && !i.respalda_restriccion && !(i.unico && i.parcial));
        if (idx.length) {
            L.push('**Índices de apoyo:**');
            L.push('');
            for (const i of idx) L.push(`- ${cod(i.nombre)}: ${cod(i.definicion.replace(/^CREATE (UNIQUE )?INDEX \S+ ON /, ''))}`);
            L.push('');
        }
        const trs = triggers.filter((x) => x.tabla === nombre);
        if (trs.length) {
            L.push('**Disparadores:**');
            L.push('');
            for (const x of trs) L.push(`- ${cod(x.nombre)}${x.habilitado === 'A' ? ' (ENABLE ALWAYS)' : ''}: ${cod(x.definicion.replace(/^CREATE TRIGGER \S+ /, ''))}`);
            L.push('');
        }
        const pols = politicas.filter((x) => x.tabla === nombre);
        if (pols.length) {
            L.push(`**Políticas RLS (${pols.length}, todas ${pols[0].cmd}):** ${pols.map((p) => cod(p.nombre)).join(', ')}`);
            L.push('');
        }
    }
}

// ---- Tipos enumerados ----
const enums = consultaJson(`
select coalesce(json_agg(x order by x.tipo), '[]'::json) from (
  select t.typname as tipo, array_agg(e.enumlabel order by e.enumsortorder) as valores
    from pg_type t join pg_namespace n on n.oid = t.typnamespace join pg_enum e on e.enumtypid = t.oid
   where n.nspname = 'public' group by t.typname
) x`);
L.push('## Tipos enumerados (dominios cerrados)');
L.push('');
L.push(`La base define ${enums.length} tipos \`ENUM\` en \`public\` (13 de la especificación, Tabla 13, más \`tipo_camara\`). Se usan como dominio cerrado de las columnas indicadas.`);
L.push('');
L.push('| Tipo | Valores | Columnas que lo usan |');
L.push('|---|---|---|');
for (const e of enums) {
    const usos = columnas.filter((c) => c.tipo === e.tipo && baseTablas.some((t) => t.tabla === c.tabla)).map((c) => `${c.tabla}.${c.columna}`);
    L.push(`| ${cod(e.tipo)} | ${e.valores.map(cod).join(', ')} | ${usos.join(', ')} |`);
}
L.push('');

// ---- Vistas ----
L.push('## Vista');
L.push('');
for (const v of vistas) {
    const cols = columnas.filter((c) => c.tabla === v.tabla);
    L.push(`### ${v.tabla}`);
    L.push('');
    L.push(`**Propósito:** ${v.comentario}`);
    L.push('');
    L.push('| # | Columna | Tipo |');
    L.push('|--:|---|---|');
    cols.forEach((c, i) => L.push(`| ${i + 1} | ${cod(c.columna)} | ${esc(tipoCorto(c.tipo))} |`));
    L.push('');
    L.push('La vista no almacena datos: se calcula en cada consulta (spec 3.4) y se crea con `security_invoker`, de modo que la RLS de quien consulta decide qué filas ve.');
    L.push('');
}

// ---- Tablas internas del esquema app ----
const app = consultaJson(`
select coalesce(json_agg(x order by x.tabla, x.pos), '[]'::json) from (
  select c.relname as tabla, a.attnum as pos, a.attname as columna, format_type(a.atttypid, a.atttypmod) as tipo,
         not a.attnotnull as admite_nulo, pg_get_expr(d.adbin, d.adrelid) as defecto,
         obj_description(c.oid, 'pg_class') as comentario, c.relrowsecurity as rls
    from pg_class c join pg_namespace n on n.oid = c.relnamespace
    join pg_attribute a on a.attrelid = c.oid and a.attnum > 0 and not a.attisdropped
    left join pg_attrdef d on d.adrelid = a.attrelid and d.adnum = a.attnum
   where n.nspname = 'app' and c.relkind = 'r'
) x`);
const appRest = consultaJson(`
select coalesce(json_agg(x order by x.tabla, x.nombre), '[]'::json) from (
  select c.conrelid::regclass::text as tabla, c.conname as nombre, pg_get_constraintdef(c.oid) as definicion
    from pg_constraint c join pg_namespace n on n.oid = c.connamespace where n.nspname = 'app'
) x`);
L.push('## Tablas internas del esquema `app` (no expuestas por la API)');
L.push('');
for (const nombre of [...new Set(app.map((c) => c.tabla))]) {
    const cols = app.filter((c) => c.tabla === nombre);
    L.push(`### app.${nombre}`);
    L.push('');
    L.push(`**Propósito:** ${cols[0].comentario}`);
    L.push('');
    L.push(`**RLS:** ${cols[0].rls ? 'habilitado (sin políticas: ningún rol de la API accede)' : 'no habilitado; los privilegios se revocan a los roles de la API (migración 0236)'}`);
    L.push('');
    L.push('| # | Columna | Tipo | Nulo | Por omisión |');
    L.push('|--:|---|---|:-:|---|');
    cols.forEach((c, i) => L.push(`| ${i + 1} | ${cod(c.columna)} | ${esc(tipoCorto(c.tipo))} | ${c.admite_nulo ? 'sí' : 'no'} | ${c.defecto ? esc(cod(c.defecto)) : ''} |`));
    L.push('');
    const rr = appRest.filter((r) => r.tabla === `app.${nombre}` || r.tabla === nombre);
    if (rr.length) {
        L.push('**Restricciones:**');
        L.push('');
        for (const r of rr) L.push(`- ${cod(r.nombre)}: ${cod(r.definicion)}`);
        L.push('');
    }
}

L.push('## Esquemas `auth`, `storage` y `supabase_migrations` en la base local');
L.push('');
L.push('Esas tablas (`auth.users`, `storage.buckets`, `storage.objects`, `supabase_migrations.schema_migrations`, `supabase_migrations.seed_runs`)');
L.push('las emula `supabase/local/00_supabase_stubs.sql` solo en PostgreSQL local; en Supabase real las provee la plataforma. No forman');
L.push('parte del modelo de SUSAN y por eso no se documentan aquí.');
L.push('');

writeFileSync(join(AQUI, 'diccionario.md'), L.join('\n'));
console.log(`diccionario.md: ${L.length} líneas; ${baseTablas.length} tablas, ${vistas.length} vista(s), ${app.length} columnas app`);
console.log('diferencias-spec.json:', JSON.stringify(diferencias.totales), 'extra:', diferencias.columnas_extra.length, 'faltantes:', diferencias.columnas_faltantes.length);
